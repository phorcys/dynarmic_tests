static const unsigned char Rcon[11] = {0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36};
static unsigned char round_keys[176];

static unsigned char xtime(unsigned char x) { return ((x << 1) ^ (((x >> 7) & 1) * 0x1b)); }
static unsigned char multiply(unsigned char x, unsigned char y) {
    unsigned char r = 0, t = x;
    int i;
    for (i = 0; i < 8; i++) { if (y & 1) r ^= t; t = xtime(t); y >>= 1; }
    return r;
}

static void sub_bytes(unsigned char *s) { int i; for (i = 0; i < 16; i++) s[i] = sbox[s[i]]; }
static void inv_sub_bytes(unsigned char *s) { int i; for (i = 0; i < 16; i++) s[i] = inv_sbox[s[i]]; }
static void add_round_key(unsigned char *s, unsigned char *k) { int i; for (i = 0; i < 16; i++) s[i] ^= k[i]; }

// ShiftRows for column-major state: rows are s[0,4,8,12], s[1,5,9,13], s[2,6,10,14], s[3,7,11,15]
static void shift_rows(unsigned char *s) {
    unsigned char t;
    t=s[1];s[1]=s[5];s[5]=s[9];s[9]=s[13];s[13]=t;  // Row 1 left 1
    t=s[2];s[2]=s[10];s[10]=t; t=s[6];s[6]=s[14];s[14]=t;  // Row 2 left 2
    t=s[15];s[15]=s[11];s[11]=s[7];s[7]=s[3];s[3]=t;  // Row 3 left 3 (= right 1)
}
static void inv_shift_rows(unsigned char *s) {
    unsigned char t;
    t=s[13];s[13]=s[9];s[9]=s[5];s[5]=s[1];s[1]=t;  // Row 1 right 1
    t=s[2];s[2]=s[10];s[10]=t; t=s[6];s[6]=s[14];s[14]=t;  // Row 2 right 2
    t=s[3];s[3]=s[7];s[7]=s[11];s[11]=s[15];s[15]=t;  // Row 3 right 3 (= left 1)
}

// MixColumns: each column s[c*4..c*4+3] is transformed
static void mix_columns(unsigned char *s) {
    for (int c = 0; c < 4; c++) {
        int i = c * 4;
        unsigned char a=s[i], b=s[i+1], d=s[i+2], e=s[i+3];
        s[i]   = multiply(2,a)^multiply(3,b)^d^e;
        s[i+1] = a^multiply(2,b)^multiply(3,d)^e;
        s[i+2] = a^b^multiply(2,d)^multiply(3,e);
        s[i+3] = multiply(3,a)^b^d^multiply(2,e);
    }
}
static void inv_mix_columns(unsigned char *s) {
    for (int c = 0; c < 4; c++) {
        int i = c * 4;
        unsigned char a=s[i], b=s[i+1], d=s[i+2], e=s[i+3];
        s[i]   = multiply(0x0e,a)^multiply(0x0b,b)^multiply(0x0d,d)^multiply(0x09,e);
        s[i+1] = multiply(0x09,a)^multiply(0x0e,b)^multiply(0x0b,d)^multiply(0x0d,e);
        s[i+2] = multiply(0x0d,a)^multiply(0x09,b)^multiply(0x0e,d)^multiply(0x0b,e);
        s[i+3] = multiply(0x0b,a)^multiply(0x0d,b)^multiply(0x09,d)^multiply(0x0e,e);
    }
}

static void key_expansion(const unsigned char *key) {
    for (int i = 0; i < 16; i++) round_keys[i] = key[i];
    int bytes_generated = 16, rcon_iteration = 1;
    unsigned char temp[4];
    while (bytes_generated < 176) {
        for (int i = 0; i < 4; i++) temp[i] = round_keys[bytes_generated - 4 + i];
        if (bytes_generated % 16 == 0) {
            unsigned char t = temp[0]; temp[0] = temp[1]; temp[1] = temp[2]; temp[2] = temp[3]; temp[3] = t;
            for (int i = 0; i < 4; i++) temp[i] = sbox[temp[i]];
            temp[0] ^= Rcon[rcon_iteration++];
        }
        for (int i = 0; i < 4; i++) { round_keys[bytes_generated] = round_keys[bytes_generated - 16] ^ temp[i]; bytes_generated++; }
    }
}

static void aes128_encrypt(unsigned char *block, const unsigned char *key) {
    test_printstr("A: key_expansion start\n");
    key_expansion(key);
    test_printstr("B: key_expansion done\n");
    add_round_key(block, round_keys);
    test_printstr("C: add_round_key done\n");
    int debug_count = 0;
    for (int round = 1; round < 10; round++) {
        debug_count++;
        if (debug_count > 20) {
            test_printstr("ERROR: too many iterations!\n");
            break;
        }
        test_printstr("round=");
        test_printint(round);
        test_printstr("\n");
        sub_bytes(block); shift_rows(block); mix_columns(block); add_round_key(block, round_keys + round * 16);
    }
    test_printstr("Loop done, rounds=");
    test_printint(debug_count);
    test_printstr("\n");
    sub_bytes(block); shift_rows(block); add_round_key(block, round_keys + 160);
}

static void aes128_decrypt(unsigned char *block, const unsigned char *key) {
    key_expansion(key);
    add_round_key(block, round_keys + 160);
    for (int round = 9; round >= 1; round--) {
        inv_shift_rows(block); inv_sub_bytes(block); add_round_key(block, round_keys + round * 16); inv_mix_columns(block);
    }
    inv_shift_rows(block); inv_sub_bytes(block); add_round_key(block, round_keys);
}

int test_main(void) {
    test_printstr("T0: start\n");
    unsigned char key[16] = {0x2b,0x7e,0x15,0x16,0x28,0xae,0xd2,0xa6,0xab,0xf7,0x15,0x88,0x09,0xcf,0x4f,0x3c};
    unsigned char pt[16]  = {0x32,0x43,0xf6,0xa8,0x88,0x5a,0x30,0x8d,0x31,0x31,0x98,0xa2,0xe0,0x37,0x07,0x34};
    unsigned char expected[16] = {0x39,0x25,0x84,0x1d,0x02,0xdc,0x09,0xfb,0xdc,0x11,0x85,0x97,0x19,0x6a,0x0b,0x32};
    unsigned char block[16];
    int match, i;
    
    test_printstr("T1: before copy loop\n");
    for (i = 0; i < 16; i++) block[i] = pt[i];
    test_printstr("T2: after copy loop\n");
    aes128_encrypt(block, key);
    match = 1; for (i = 0; i < 16; i++) if (block[i] != expected[i]) { match = 0; break; }
    TEST_ASSERT(match);
    
    aes128_decrypt(block, key);
    match = 1; for (i = 0; i < 16; i++) if (block[i] != pt[i]) { match = 0; break; }
    TEST_ASSERT(match);
    
    test_pass();
    return 0;
}
