.text
.global _start
_start:
    // 浮点下溢测试
    // 非常小的数相乘导致下溢
    
    // 最小规格化单精度浮点数 ≈ 1.175e-38
    // 二进制: 0x00800000 (指数=1, 尾数=0)
    
    mov w8, #0x00800000        // 最小规格化 float
    fmov s0, w8
    
    // s0 * s0 = 下溢到非规格化数或零
    fmul s1, s0, s0
    
    // 检查结果是否接近零或非规格化
    fmov w0, s1
    
    // 结果应该是 0x00000000 (下溢到零) 或非常小的非规格化数
    
    brk #0
